namespace Bellerophon.Generator.Emitters
{
    using System.Text;

    /// <summary>
    /// Accumulates indented lines of generated C#.  Output uses <c>\n</c> line endings on every platform, so identical models
    /// produce byte-identical code.
    /// </summary>
    internal sealed class CodeWriter
    {
        /// <summary>
        /// The generated text.
        /// </summary>
        private readonly StringBuilder builder = new StringBuilder();

        /// <summary>
        /// The current indentation level.
        /// </summary>
        private int indent;

        /// <summary>
        /// Writes the standard header of a generated file.
        /// </summary>
        public void Header()
        {
            this.Line("// <auto-generated>");
            this.Line("//     Generated by Bellerophon from the model file. Changes to this file will be lost when it is regenerated.");
            this.Line("// </auto-generated>");
            this.Line("#nullable enable");
            this.Line();
        }

        /// <summary>
        /// Writes a line at the current indentation; an empty call writes a blank line.
        /// </summary>
        /// <param name="text">The text.</param>
        public void Line(string text = "")
        {
            if (text.Length > 0)
            {
                this.builder.Append(' ', this.indent * 4);
            }

            this.builder.Append(text).Append('\n');
        }

        /// <summary>
        /// Opens a brace block.
        /// </summary>
        public void Open()
        {
            this.Line("{");
            this.indent++;
        }

        /// <summary>
        /// Closes a brace block.
        /// </summary>
        public void Close()
        {
            this.indent--;
            this.Line("}");
        }

        /// <summary>
        /// Closes a block with a suffix after the brace, such as the semicolon that ends an initializer.
        /// </summary>
        /// <param name="suffix">The text after the closing brace.</param>
        public void Close(string suffix)
        {
            this.indent--;
            this.Line("}" + suffix);
        }

        /// <summary>
        /// Writes an XML documentation summary.
        /// </summary>
        /// <param name="text">The summary text.</param>
        public void Summary(string text)
        {
            this.Line("/// <summary>");
            this.Line($"/// {Escape(text)}");
            this.Line("/// </summary>");
        }

        /// <inheritdoc/>
        public override string ToString() => this.builder.ToString();

        /// <summary>
        /// Escapes text for an XML documentation comment.
        /// </summary>
        /// <param name="text">The text.</param>
        /// <returns>The escaped text.</returns>
        private static string Escape(string text) =>
            text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\n", " ").Replace("\r", string.Empty);
    }
}
